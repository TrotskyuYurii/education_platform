/**
 * Вимоги до питань. Перший пункт — скільки питань скласти: для нової
 * інструкції це весь банк, для догенерації — лише додаткова порція.
 */
function buildQuestionRules(countRule: string): string {
  return `ВИМОГИ ДО ТЕСТОВИХ ПИТАНЬ:
1. ${countRule}
2. Розподіл складності: приблизно третина easy, половина medium, решта hard.
3. Банк має покривати весь документ: кожен розділ і крок, Ключові поля та реквізити, кожен пункт СТОП-СПИСКІВ, Автоматичні дії системи та таблицю відповідальності. Не зосереджуйся лише на початку інструкції.
4. Кожне питання перевіряє окремий факт або окрему ситуацію. Не перефразовуй одне й те саме питання кілька разів.
5. Кожне питання самодостатнє: не посилайся на інші питання («як у попередньому питанні») — питання показуються у випадковому порядку.
6. Варіанти відповідей теж перемішуються, тому не використовуй варіанти, що залежать від позиції («Усі перелічені», «Варіанти А і Б», «Жоден з наведених»). Неправильні варіанти мають бути правдоподібними і приблизно такої ж довжини, як правильний.
7. Запитання обов'язково повинні спиратися на текст інструкції, а не на загальні знання.
8. Рівно один варіант відповіді має бути позначений як правильний через [x].
9. У відповіді виводь виключно готовий текст Markdown без вступних слів, привітань та сторонніх коментарів.`;
}

