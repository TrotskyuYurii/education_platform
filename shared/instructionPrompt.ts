/**
 * Промпт для догенерації питань до вже завантаженої інструкції: наприклад,
 * для матеріалів, імпортованих ще тоді, коли ШІ складав лише 3–6 питань.
 * Модель бачить наявні питання, щоб не повторювати їх.
 */
export function buildAdditionalQuestionsPrompt(params: {
  instructionMarkdown: string;
  existingQuestions: string[];
  count: number;
}): string {
  const existing = params.existingQuestions.length > 0
    ? params.existingQuestions.map(q => `- ${q}`).join('\n')
    : '- (питань ще немає)';

  return `Ти — провідний експерт з корпоративного навчання та укладання професійних тестів.
Нижче наведено робочу інструкцію компанії та перелік питань, які вже є в її банку тестування.
Твоє завдання: доповнити банк НОВИМИ питаннями, які не дублюють наявні.

ІНСТРУКЦІЯ:
<<<
${params.instructionMarkdown}
>>>

ПИТАННЯ, ЯКІ ВЖЕ Є В БАНКУ (не повторюй і не перефразовуй їх):
${existing}

Формат кожного питання:

${QUESTION_TEMPLATE}

${buildQuestionRules(
    `Склади рівно ${params.count} нових запитань. Віддавай перевагу тим частинам інструкції, яких наявні питання ще не торкаються.`
  )}
Виводь лише блоки «### ПИТАННЯ:» — без назви інструкції, метаданих та інших розділів.`;
}
