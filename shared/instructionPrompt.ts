export interface AvailableImage {
  /** Ім'я файлу в теці assets/, наприклад img-001.png */
  fileName: string;
  page?: number;
  width?: number;
  height?: number;
}

/**
 * Правила щодо зображень. Головне: жодного base64 — платформа зберігає скріншоти
 * окремими файлами у теці документа, а Markdown лише посилається на них.
 */
export const IMAGE_RULES = `ПРАВИЛА ЩОДО ЗОБРАЖЕНЬ (ОБОВ'ЯЗКОВІ):
1. КАТЕГОРИЧНО ЗАБОРОНЕНО вбудовувати зображення у файл кодом Base64 (\`data:image/...;base64,...\`) — такі вставки система видалить, а документ стане неповним.
2. Скріншоти та схеми з оригіналу вже збережені платформою окремими файлами у теці \`assets/\` поруч із .md файлом. Посилайся лише на них.
3. Формат посилання — відносний шлях без домену: \`![Змістовний підпис до скріншота](assets/img-001.png)\`.
4. Дозволено використовувати ВИКЛЮЧНО ті імена файлів, що перелічені нижче у блоці «ДОСТУПНІ ЗОБРАЖЕННЯ». Не вигадуй власних імен і не посилайся на зовнішні сайти — посилання на неіснуючий файл буде прибране разом із підписом.
5. Постав кожне зображення точно в те місце тексту або в той крок, якого воно стосується (орієнтир — номер сторінки біля імені файлу). Одне зображення використовується один раз.
6. Якщо зображення не стосується жодного кроку чи розділу — просто не вставляй його.`;

/** Блок із переліком файлів, які модель має право використати. */
export function buildAvailableImagesBlock(images: AvailableImage[] = []): string {
  if (images.length === 0) {
    return `ДОСТУПНІ ЗОБРАЖЕННЯ: немає.
У цьому документі не знайдено придатних скріншотів, тому НЕ вставляй у Markdown жодного посилання на зображення.`;
  }

  const lines = images.map(img => {
    const details = [
      img.page ? `сторінка ${img.page}` : null,
      img.width && img.height ? `${img.width}×${img.height} px` : null
    ].filter(Boolean).join(', ');
    return `- assets/${img.fileName}${details ? ` — ${details}` : ''}`;
  });

  return `ДОСТУПНІ ЗОБРАЖЕННЯ (вже збережені платформою у теці assets/, порядок відповідає порядку появи в документі):
${lines.join('\n')}`;
}

/**
 * Блок про підрозділи: модель обирає з довідника, а не вигадує власну назву.
 *
 * Раніше в промпті стояв приклад («Відділ роздрібного продажу / Казначейство /
 * …»), і модель на кожен документ придумувала свій варіант назви. Через це в
 * додатку з'являлися підрозділи, яких немає в оргструктурі, а фільтри
 * розросталися дублікатами одного й того ж відділу.
 */
export function buildDepartmentsBlock(departments: string[] = []): string {
  const known = departments
    .map(name => (name || '').trim())
    .filter(name => name && !isDefaultDepartment(name));

  if (known.length === 0) {
    return `ПІДРОЗДІЛИ (ОБОВ'ЯЗКОВІ ПРАВИЛА):
У додатку ще не заведено жодного профільного підрозділу, тому в полі «Підрозділ» вкажи рівно «${DEFAULT_DEPARTMENT}» і нічого іншого.`;
  }

  return `ПІДРОЗДІЛИ (ОБОВ'ЯЗКОВІ ПРАВИЛА):
1. У полі «Підрозділ» дозволено вказати ВИКЛЮЧНО одну назву зі списку нижче, скопійовану символ у символ. Створювати власні назви підрозділів заборонено.
2. Проаналізуй зміст інструкції та обери той підрозділ, чиї співробітники виконують описані в ній дії.
3. Якщо жодна назва зі списку не підходить впевнено або інструкція стосується всієї компанії — вкажи «${DEFAULT_DEPARTMENT}».
4. Не дописуй до назви пояснень, дужок і не перелічуй кілька варіантів через кому — тільки одна назва зі списку.

ДОСТУПНІ ПІДРОЗДІЛИ:
${known.map(name => `- ${name}`).join('\n')}
- ${DEFAULT_DEPARTMENT} (загальний — коли впевненого збігу немає)`;
}

